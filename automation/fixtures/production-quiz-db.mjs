// Synthetic-only scaffold from committed schema/function definitions. Never connects to Supabase.
import fs from 'node:fs/promises';
import {PGlite} from '../../tmp/quiz-runtime/node_modules/@electric-sql/pglite/dist/index.js';
const quote=s=>'"'+s.replaceAll('"','""')+'"';
export async function setupProductionQuizDB(){
 const db=new PGlite(),schema=JSON.parse(await fs.readFile('automation/fixtures/partner-match-before/schema.json','utf8'));
 try{
 await db.exec(`create role anon;create role authenticated;create role service_role;create schema auth;create schema partner_pilot;create schema realtime;create schema storage;
 create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz,raw_app_meta_data jsonb default '{"providers":["google"]}');
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 create function auth.jwt() returns jsonb language sql stable security definer set search_path='' as $$select jsonb_build_object('email',email,'sub',id,'app_metadata',raw_app_meta_data) from auth.users where id=auth.uid()$$;
 create function public.is_teacher() returns boolean language sql stable as $$select exists(select 1 from auth.users where id=auth.uid() and email='teacher@example.invalid')$$;
 create function public.grade3_google_ready() returns boolean language sql stable as $$select true$$;
 create function realtime.send(jsonb,text,text,boolean) returns void language plpgsql as $$begin end$$;
 set check_function_bodies=off;grant usage on schema public,auth to anon,authenticated,service_role;`);
 for(const t of schema.tables.filter(t=>t.kind==='r'||t.kind==='p')){
  const cols=t.columns.map(c=>quote(c.name)+' '+c.type+(c.identity?' generated by default as identity':c.generated?' generated always as ('+c.default+') stored':'')).join(',');
  await db.exec(`create table ${quote(t.schema)}.${quote(t.name)}(${cols})`);
 }
 for(const s of schema.sequences){const ns=s.schema||'public';if(!(await db.query('select to_regclass($1) id',[ns+'.'+s.name])).rows[0].id)await db.exec(`create sequence ${quote(ns)}.${quote(s.name)}`);}
 for(const t of schema.tables.filter(t=>t.kind==='r'||t.kind==='p'))for(const c of t.columns){
  if(c.default&&!c.identity&&!c.generated)await db.exec(`alter table ${quote(t.schema)}.${quote(t.name)} alter column ${quote(c.name)} set default ${c.default}`);
  if(c.not_null)await db.exec(`alter table ${quote(t.schema)}.${quote(t.name)} alter column ${quote(c.name)} set not null`);
 }
 await db.exec(await fs.readFile('automation/fixtures/partner-match-before/functions.sql','utf8'));
 // The production teacher allowlist is an external-auth boundary; keep a synthetic teacher here.
 await db.exec(`create or replace function public.is_teacher() returns boolean language sql stable security definer set search_path='' as $$select exists(select 1 from auth.users where id=auth.uid() and email='teacher@example.invalid')$$`);
 for(const foreign of [false,true])for(const t of schema.tables.filter(t=>t.kind==='r'||t.kind==='p'))for(const c of t.constraints){
  if(c.def.startsWith('FOREIGN KEY')!==foreign)continue;
  await db.exec(`alter table ${quote(t.schema)}.${quote(t.name)} add constraint ${quote(c.name)} ${c.def}`);
 }
 for(const t of schema.tables.filter(t=>t.kind==='r'||t.kind==='p'))if(t.rls)await db.exec(`alter table ${quote(t.schema)}.${quote(t.name)} enable row level security`);
 // Trigger installation is explicit in individual suites; no real catalog/growth event is consumed.
 const uid=n=>`00000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
 const as=async(n,role='authenticated')=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[n?uid(n):'']);await db.exec('set role '+role);};
 return{db,uid,as};
 }catch(e){await db.close();throw e;}
}
