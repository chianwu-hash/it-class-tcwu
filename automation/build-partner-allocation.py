"""Compile reviewed source structure into private-server allocation metadata (no question text).

The runtime joins exact pinned versions to the immutable partner copy. Shared fields and
unencoded option pools are conservatively co-owned; unavailable source targets stay unavailable.
"""
import argparse
import hashlib
import json
from pathlib import Path


def compile_paper(paper, decision):
    units = paper['units']
    parent = list(range(len(units)))

    def root(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    def union(indices):
        indices = sorted(set(indices))
        for i in indices[1:]:
            parent[root(i)] = root(indices[0])

    fields = {}
    for i, unit in enumerate(units):
        for q in unit['questions']:
            for ref in q['refs']:
                if 'fieldId' in ref:
                    fields.setdefault(ref['fieldId'], set()).add(i)
    for indices in fields.values():
        union(indices)
    # Co-ownership preserves possible one-to-one / no-reuse rules without inventing a rule.
    for pool in decision.get('sharedOptionPools', []):
        union([i for fid in pool['fieldIds'] for i in fields[fid]])
    packs = {}
    for i, unit in enumerate(units):
        active_questions = [q for q in unit['questions'] if any('fieldId' in r for r in q['refs'])]
        if not active_questions:
            continue
        pack = packs.setdefault(root(i), {'id': unit['id'], 'weight': 0, 'fields': {}, 'units': []})
        pack['units'].append(unit['id'])
        pack['weight'] += len(active_questions)
        for q in active_questions:
            for ref in q['refs']:
                if 'fieldId' in ref:
                    fid, gid = ref['fieldId'], ref['groupId']
                    if fid in pack['fields'] and pack['fields'][fid] != gid:
                        raise ValueError('field group mismatch')
                    pack['fields'][fid] = gid
    plan = []
    for pack in packs.values():
        pack['fields'] = [{'id': f, 'group': g} for f, g in sorted(pack['fields'].items())]
        plan.append(pack)
    if sum(len(p['fields']) for p in plan) != paper['answerFieldCount']:
        raise ValueError('field coverage mismatch')
    return {'paper': paper['paperId'], 'version': paper['activeVersion'],
            'sha256': paper['documentSha256'], 'packs': sorted(plan, key=lambda p: p['id']),
            'blockedTargets': sum(not any('fieldId' in r for r in q['refs']) for u in units for q in u['questions']),
            'unlistedAssessments': paper.get('unlistedAssessments', [])}


def build(structure, decisions):
    if structure['schemaVersion'] != 1:
        raise ValueError('unsupported structure schema')
    by_id = {p['paperId']: p for p in decisions['papers']}
    if len(by_id) != len(decisions['papers']) or len({p['paperId'] for p in structure['papers']}) != len(structure['papers']) or set(by_id) != {p['paperId'] for p in structure['papers']}:
        raise ValueError('paper scope is not unique or complete')
    return [compile_paper(p, by_id[p['paperId']]) for p in structure['papers']]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    directory = args.root / 'docs/development'
    plans = build(json.loads((directory / 'past-paper-allocation-structure.json').read_text(encoding='utf-8')),
                  json.loads((directory / 'past-paper-allocation-decisions.json').read_text(encoding='utf-8')))
    raw = json.dumps({'schemaVersion': 1, 'policy': 'whole-source-units-co-owned-option-pools-v1', 'papers': plans}, ensure_ascii=False, separators=(',', ':')) + '\n'
    target = args.root / 'supabase/partner-allocation-plan.json'
    target.write_text(raw, encoding='utf-8')
    sql = '-- Generated by automation/build-partner-allocation.py; metadata only. Install inside migration transaction.\n'
    for plan in plans:
        data = json.dumps(plan, ensure_ascii=False, separators=(',', ':'))
        if '$plan$' in data:
            raise ValueError('unsafe SQL delimiter')
        sql += "insert into partner_pilot.allocation_specs(version,source_paper,document_sha,plan) values(" + ','.join("'" + str(plan[k]).replace("'", "''") + "'" for k in ['version','paper','sha256']) + ",$plan$" + data + "$plan$::jsonb);\n"
    sql += "do $count$ begin if (select count(*) from partner_pilot.allocation_specs)<>" + str(len(plans)) + " then raise exception 'ALLOCATION_PLAN_COUNT';end if;end $count$;\n"
    template = (args.root / 'automation/templates/quiz-partner-allocation.sql').read_text(encoding='utf-8')
    if template.count('-- INSERT REVIEWED PLANS HERE') != 1:
        raise ValueError('migration template marker mismatch')
    (args.root / 'supabase/quiz-partner-allocation.sql').write_text(template.replace('-- INSERT REVIEWED PLANS HERE', sql), encoding='utf-8')
    print(json.dumps({'papers': len(plans), 'sha256': hashlib.sha256(raw.encode()).hexdigest()}))


if __name__ == '__main__':
    main()
