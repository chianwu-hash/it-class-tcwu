def page_text(text):
    return re.sub(r"\s+", "", text)


def apply(sources, spreads):
    pages = {p["page"]: (spread, page_text(p["text"])) for spread in spreads for p in spread["pages"]}
    rules = defaultdict(list)
    for lesson, page, anchors, cue, explanation in RULES:
        spread, text = pages[page]
        assert spread["lesson"], page
        assert all(anchor in text for anchor in anchors), (page, anchors)
        rules[lesson].append((page, re.compile(cue), explanation))
    for row in sources:
        if not row["passed"]:
            yield row
            continue
        material = row["prompt"] + " " + row["options"][row["answer"]-1] + " " + row["explanation"]
        evidence = []
        for page, pattern, summary in rules[row["lesson"]]:
            matches = list(pattern.finditer(material))
            if matches:
                strength = max(len(match.group()) for match in matches)
                evidence.append((strength, page, summary, matches[0].group()))
        if not evidence:
            yield {**row, "passed":False, "reason":"textbook_topic"}
            continue
        evidence.sort(key=lambda match: (-match[0], match[1]))
        primary = evidence[0]
        same = [hit for hit in evidence if hit[0] >= primary[0] and hit[1] != primary[1]]
        matches = [primary, *same[:2]]
        yield {**row, "primary":primary[1], "references":[hit[1] for hit in matches],
               "textbook_reason":primary[2],
               "textbook_matches":[{"page":hit[1], "cue":hit[3]} for hit in matches]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("sources", "spreads", "output"):
        parser.add_argument("--"+name, type=Path, required=True)
    args = parser.parse_args()
    def read(path):
        return json.loads(path.read_text(encoding="utf8"))
    out = list(apply(read(args.sources), read(args.spreads)))
    args.output.write_text(json.dumps(out,ensure_ascii=False,indent=2), encoding="utf8")
    print(Counter(row.get("reason", row.get("layout")) for row in out))


if __name__ == "__main__":
    main()
